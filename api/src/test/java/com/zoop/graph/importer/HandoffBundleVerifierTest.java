package com.zoop.graph.importer;

import java.io.IOException;
import java.io.InputStream;
import java.util.List;
import java.util.function.Consumer;

import com.zoop.common.json.Canonical;
import com.zoop.common.json.StrictJson;
import com.zoop.graph.importer.HandoffExportParser.VerifiedHandoff;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The Java port of the producer's closed validator: a real producer export (generated by
 * {@code ai/pipeline/scripts/graph_handoff_smoke.py --write-fixture}) is accepted, each of the producer's own negative fixtures
 * is refused, and every rule of the schema is broken one at a time on a synthetic bundle whose content digest is recomputed, so
 * only the targeted rule can fail.
 */
class HandoffBundleVerifierTest {
    private static byte[] resource(String name) throws IOException {
        try (InputStream in = HandoffBundleVerifierTest.class.getClassLoader().getResourceAsStream("graph-handoff/" + name)) {
            return in.readAllBytes();
        }
    }

    /** A request that pins exactly the manifest and bundle the file holds, so only the content can fail. */
    private static GraphHandoffRequest pinning(byte[] export) {
        JsonNode root = HandoffFixtures.parse(export);
        return new GraphHandoffRequest(root.get("handoffId").stringValue(), Canonical.digest(root.get("manifest")),
                Canonical.sha256(Canonical.bytes(root.get("bundle"))), "operator-a");
    }

    private static GraphHandoffFailure failureOf(byte[] export) {
        return assertThrows(GraphHandoffException.class, () -> new HandoffExportParser().parse(export, pinning(export)))
                .failure();
    }

    // ------------------------------------------------------------------------------------------------ a real export -----

    @Test
    void aRealProducerExportIsAcceptedAndItsContentIsRecomputedHere() throws Exception {
        byte[] export = resource("export-valid.json");

        VerifiedHandoff verified = new HandoffExportParser().parse(export, pinning(export));

        HandoffBundle bundle = verified.bundle();
        assertEquals("handoff-1", bundle.handoffId());
        assertEquals("synthetic", bundle.sourceKind());
        assertEquals(2, bundle.companies().size());
        assertEquals(2, bundle.issues().size());
        assertEquals(6, bundle.evidence().size());
        assertEquals(3, bundle.articles().size());
        assertEquals(4, bundle.relations().size());
        assertEquals(List.of("FOLLOWS", "INVOLVES", "INVOLVES", "STRUCTURALLY_RELATED_TO"),
                bundle.relations().stream().map(HandoffBundle.Relation::type).toList());
        assertEquals("manual-operator-review", bundle.relations().stream()
                .filter(r -> r.type().equals("STRUCTURALLY_RELATED_TO")).findFirst().orElseThrow().origin());
        assertEquals(verified.bundleDigest(), HandoffFixtures.parse(export).get("receipt").get("bundleDigest").stringValue());
        assertEquals(verified.contentDigest(), HandoffFixtures.parse(export).get("bundle").get("digests").get("content").stringValue());
    }

    @Test
    void theProducersOwnNegativeFixturesAreRefused() throws Exception {
        for (String name : List.of("bundle-forged-evidence-id.json", "bundle-missing-geography.json",
                "bundle-dangling-endpoint.json", "bundle-wrong-article-version.json", "bundle-shares-issue-edge.json")) {
            assertEquals(GraphHandoffFailure.BUNDLE_INVALID, failureOf(resource(name)), name);
        }
        for (String name : List.of("manifest-wrong-digest.json", "manifest-wrong-source-pin.json",
                "manifest-wrong-file-pin.json", "manifest-unknown-field.json", "export-missing-manifest.json")) {
            assertEquals(GraphHandoffFailure.HANDOFF_EXPORT_INVALID, failureOf(resource(name)), name);
        }
    }

    @Test
    void aWithheldEnvelopeIsNotAnExport() throws Exception {
        byte[] withheld = resource("export-withheld.json");
        GraphHandoffRequest request = new GraphHandoffRequest("handoff-1", "0".repeat(64), "0".repeat(64), "operator-a");

        assertEquals(GraphHandoffFailure.HANDOFF_EXPORT_INVALID,
                assertThrows(GraphHandoffException.class, () -> new HandoffExportParser().parse(withheld, request)).failure());
    }

    // ------------------------------------------------------------------------------------------------ one rule at a time -

    private static final HandoffFixtures.Built BUILT = HandoffFixtures.build();

    /** A copy of the valid bundle with {@code change} applied and the content digest recomputed. */
    private static JsonNode mutated(Consumer<ObjectNode> change) {
        ObjectNode copy = BUILT.bundle().deepCopy();
        change.accept(copy);
        ((ObjectNode) copy.get("digests")).put("content", HandoffBundleVerifier.contentDigest(copy));
        return copy;
    }

    private static void assertRefused(String rule, Consumer<ObjectNode> change) {
        assertThrows(StrictJson.Malformed.class, () -> HandoffBundleVerifier.verify(mutated(change)), rule);
    }

    @Test
    void theSyntheticBundleIsValid() {
        HandoffBundle bundle = HandoffBundleVerifier.verify(BUILT.bundle());

        assertEquals(1, bundle.issues().size());
        assertEquals(3, bundle.evidence().size());
        assertEquals(List.of("INVOLVES", "STRUCTURALLY_RELATED_TO"),
                bundle.relations().stream().map(HandoffBundle.Relation::type).sorted().toList());
        assertEquals(HandoffBundleVerifier.contentDigest(BUILT.bundle()),
                BUILT.bundle().get("digests").get("content").stringValue());
    }

    @Test
    void everyClosedSchemaRuleIsEnforced() {
        assertRefused("unknown top-level key", b -> b.put("operatorPath", "/private/x"));
        assertRefused("unknown nested key", b -> ((ObjectNode) b.get("provenance")).put("extra", "x"));
        assertRefused("missing key", b -> b.remove("readiness"));
        assertRefused("wrong schema version", b -> b.put("schemaVersion", "zoop-graph-handoff-bundle-2"));
        assertRefused("wrong policy version", b -> ((ObjectNode) b.get("policy")).put("version", "zoop-public-projection-policy-2"));
        assertRefused("an actual-model run is not producible", b -> ((ObjectNode) b.get("provenance")).put("executionMode", "live"));
        assertRefused("declared and observed kind differ", b -> ((ObjectNode) b.get("provenance")).put("observedSourceKind", "actual"));
        assertRefused("offset as a string", b -> ((ObjectNode) b.get("evidence").get(0)).put("start", "0"));
        assertRefused("offset not before end", b -> ((ObjectNode) b.get("evidence").get(0)).put("end", 0));
        assertRefused("bad hash", b -> ((ObjectNode) b.get("evidence").get(0)).put("quoteSha256", "XYZ"));
        assertRefused("readiness claims activation", b -> ((ObjectNode) b.get("readiness")).put("publicActivation", "active"));
        assertRefused("checks list changed", b -> ((ArrayNode) b.get("checks").get("appImportPending")).remove(0));
        assertRefused("input kind", b -> ((ObjectNode) b.get("evidence").get(0).get("source")).put("inputKind", "summary"));
        assertRefused("unknown relation type", b -> ((ObjectNode) b.get("relations").get(0)).put("type", "SHARES_ISSUE"));
        assertRefused("geography class", b -> ((ObjectNode) b.get("issues").get(0).get("geography")).put("value", "unknown"));
        assertRefused("geography policy", b -> ((ObjectNode) b.get("issues").get(0).get("geography")).put("policyVersion", "x"));
        assertRefused("time precision outside the set", b -> ((ObjectNode) b.get("issues").get(0)).put("timePrecision", "hour"));
        assertRefused("publication precision pair", b -> ((ObjectNode) b.get("articles").get(0)).put("publicationPrecision", "unknown"));
        assertRefused("day without a date", b -> {
            ((ObjectNode) b.get("articles").get(0)).put("publicationPrecision", "day");
            ((ObjectNode) b.get("articles").get(0)).put("publishedAt", "2026-10-08T00:00:00Z");
        });
    }

    @Test
    void everyReferenceFormulaAndCountIsRecomputed() {
        String foreign = "ev-" + "0".repeat(64);
        assertRefused("evidence id is not the app formula", b -> ((ObjectNode) b.get("evidence").get(0)).put("id", foreign));
        assertRefused("evidence of an unknown article", b -> ((ObjectNode) b.get("evidence").get(0)).put("articleVersion", "f".repeat(64)));
        assertRefused("issue cites unknown evidence", b -> ((ArrayNode) b.get("issues").get(0).get("evidenceIds")).add(foreign));
        assertRefused("evidence ids not sorted", b -> {
            ArrayNode ids = (ArrayNode) b.get("issues").get(0).get("evidenceIds");
            JsonNode first = ids.remove(0);
            ids.add(first);
        });
        assertRefused("relation endpoint missing", b -> ((ObjectNode) b.get("relations").get(0)).put("target", "KRX:999999"));
        assertRefused("relation id is not the edge formula", b -> ((ObjectNode) b.get("relations").get(0)).put("id", "edge-" + "0".repeat(64)));
        assertRefused("structural relation without its basis", b -> {
            for (JsonNode relation : b.get("relations").values()) {
                if (relation.get("type").stringValue().equals("STRUCTURALLY_RELATED_TO")) {
                    ((ArrayNode) relation.get("basis")).removeAll();
                }
            }
        });
        assertRefused("source ref to a review that was not used", b -> ((ObjectNode) b.get("relations").get(0).get("sourceRefs").get(0))
                .put("id", "rc-" + "9".repeat(64)));
        assertRefused("counts", b -> ((ObjectNode) b.get("counts")).put("evidence", 4));
        assertRefused("relation counts", b -> ((ObjectNode) b.get("counts").get("relations")).put("FOLLOWS", 1));
        assertRefused("orphan company", b -> {
            ObjectNode company = ((ArrayNode) b.get("companies")).addObject();
            company.put("id", "KRX:111111");
            company.put("canonicalId", "co:orphan");
            company.put("label", "고아");
            company.put("decisionRef", "d");
            ((ObjectNode) b.get("counts")).put("companies", 3);
        });
        assertRefused("an issue that shares a company id", b -> ((ObjectNode) b.get("issues").get(0)).put("id", HandoffFixtures.COMPANY_A));
        assertRefused("exclusion counts do not match its items", b -> ((ObjectNode) b.get("exclusions").get("counts")).put("issue_unreviewed", 1));
        assertRefused("source event of an unpinned upstream", b -> ((ObjectNode) b.get("issues").get(0).get("sourceEvents").get(0)
                .get("upstream")).put("jobId", "other-upstream"));
        assertRefused("basis countries differ from the verdict", b -> ((ArrayNode) b.get("issues").get(0).get("geography").get("basis")
                .get(0).get("countries")).add("US"));
        assertRefused("structural provenance is not a manual assertion", b -> {
            for (JsonNode relation : b.get("relations").values()) {
                if (relation.get("type").stringValue().equals("STRUCTURALLY_RELATED_TO")) {
                    ((ObjectNode) relation.get("provenance")).put("status", "verified");
                }
            }
        });
    }

    @Test
    void theContentDigestIsRebuiltNotTrusted() {
        ObjectNode copy = BUILT.bundle().deepCopy();
        ((ObjectNode) copy.get("companies").get(0)).put("label", "다른 이름");

        assertThrows(StrictJson.Malformed.class, () -> HandoffBundleVerifier.verify(copy));
    }

    @Test
    void sortedUniqueFollowsCodePointOrderLikeThePythonProducer() {
        // U+1F600 (two UTF-16 units) sorts AFTER U+FF5E by code point, but before it in UTF-16 order.
        String emoji = "\uD83D\uDE00";
        String fullwidth = "\uFF5E";
        assertTrue(HandoffBundleVerifier.compareCodePoints(emoji, fullwidth) > 0);
        assertTrue(emoji.compareTo(fullwidth) < 0);
        assertTrue(HandoffBundleVerifier.sortedUnique(List.of("a", "b", fullwidth, emoji)));
        assertFalse(HandoffBundleVerifier.sortedUnique(List.of("a", emoji, fullwidth)));
        assertFalse(HandoffBundleVerifier.sortedUnique(List.of("a", "a")));
        assertEquals("domestic", HandoffBundleVerifier.countriesClass(List.of("KR")));
        assertEquals("international", HandoffBundleVerifier.countriesClass(List.of("KR", "US")));
        assertEquals("invalid", HandoffBundleVerifier.countriesClass(List.of("kr")));
        assertEquals("unknown", HandoffBundleVerifier.countriesClass(List.of()));
    }
}
