        verdictsOf(ordered).add(verdictOn(ordered, 0, "period", "ALLOW", "stated", eventEvidence(ordered, 0)));
        verdictsOf(ordered).add(verdictOn(ordered, 1, "eventTime", "ALLOW", "stated", eventEvidence(ordered, 1)));
