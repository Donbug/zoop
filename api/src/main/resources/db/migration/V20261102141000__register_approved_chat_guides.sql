## 줍은 어떤 서비스인가요

줍(Zoop)은 내 종목과 시장 사건이 왜 연결되는지를 근거 자료와 함께 보여 주는 금융 지도 서비스입니다. 공시와 기사에서 확인된 사건을 기업과 이어, 어떤 일이 어떤 근거로 내 종목과 연결되는지 보여 줍니다.

줍의 핵심 기능은 다음과 같습니다.

- **지도**: 기업과 사건을 점으로, 그 사이의 관계를 선으로 보여 줍니다.
- **근거**: 관계와 사건을 뒷받침하는 기사·공시의 인용 구간을 확인합니다.
- **종목**과 기업 상세: 기업을 찾고 시세, 차트, 사건 타임라인, 문서, 재무, 관계 그래프를 봅니다.
- **브리핑**: 출근·퇴근 회차별로 시장 요약과 핵심 이슈를 읽습니다.
- **내 종목**: 관심 종목과 가상 계좌의 모의 보유 종목을 관리합니다.
- **AI 질문**: 궁금한 점을 물으면 근거 수준을 구분해 답합니다.

줍은 투자 권유를 제공하지 않습니다. 매수·매도 판단이나 추천을 하지 않으며, 화면의 관계와 전망은 판단을 돕는 참고 자료입니다.

## 로그인 없이 무엇을 쓸 수 있나요

로그인 화면의 **로그인 없이 둘러보기**를 누르면 가입 없이 쓸 수 있습니다.

- 바로 쓸 수 있는 기능: 시장 전체 지도, 공개 브리핑, 기업 정보
- 로그인이 필요한 기능: 관심 종목 설정, 가상 계좌 연결, 내 종목 지도, AI 질문, 브리핑 평가

둘러보는 중에는 화면 위쪽에 "비회원 체험 중 · 로그인" 표시가 있습니다. 언제든 로그인하거나 가입하면 모든 기능을 쓸 수 있습니다. 지도에서 내 종목을 고르거나 AI 질문 창을 열면 로그인 안내가 나옵니다. 내 종목 메뉴를 누르면 로그인 화면으로 이동합니다.

## 가입하고 로그인하려면

로그인 화면에서 이메일과 비밀번호로 로그인하거나, 구글·카카오톡 로그인을 쓸 수 있습니다. 계정이 없으면 **이메일로 회원가입**을 누릅니다.

이메일 가입에는 이메일, 비밀번호, 필수 약관 동의가 필요하고 표시 이름은 선택입니다. 비밀번호는 8자 이상 32자 이하이며, 제어 문자와 흔한 비밀번호는 쓸 수 없습니다. 약관은 항목별로 체크하거나 **모두 동의**를 누릅니다.

소셜 계정으로 처음 가입할 때는 소셜 계정에서 확인한 이메일을 쓰므로 표시 이름과 약관 동의만 확인하면 됩니다. 소셜 로그인에는 이메일 제공 동의가 필요합니다.

자주 나오는 안내는 다음과 같습니다.

- "이미 이메일로 가입한 계정이에요": 이메일로 로그인한 뒤 계정 메뉴에서 소셜 계정을 연결합니다.
- "이용이 제한된 계정이에요": 고객센터로 문의합니다.
- "로그인 시도가 많아요": 잠시 뒤 다시 시도합니다.

로그인한 뒤에는 화면 오른쪽 위의 계정 메뉴에서 이름과 이메일을 확인하고, Google·카카오 계정을 연결하거나 로그아웃할 수 있습니다.

## 처음 가입하면 무엇을 하나요

가입한 뒤에는 초기 설정을 마쳐야 지도와 내 종목을 쓸 수 있습니다. 설정을 마치지 않고 지도로 가면 초기 설정 화면으로 돌아옵니다.

1. **투자 여부** 선택: "지금 주식에 투자하고 있어요" 또는 "아직 투자하지 않아요"를 고릅니다.
2. **가상 계좌** 연결: 투자 중이라고 고르면 이어집니다. 실제 증권 계좌가 아니라 준비된 모의 데이터로 만든 계좌입니다. 계좌를 고르면 보유 종목과 평가 기준을 미리 보고 연결합니다. **건너뛰고 관심 종목 고르기**로 넘어갈 수 있습니다.
3. 관심 종목 선택: 기업명이나 종목 코드로 검색해 고릅니다. 고른 종목을 중심으로 내 종목 지도를 보여 줍니다. **고르지 않고 지도 보기**로 건너뛸 수 있고, 이때 보유 종목이 없으면 시장 전체 지도가 열립니다.

여기서 고른 내용은 나중에 내 종목 메뉴에서 언제든 바꿀 수 있습니다.

처음 지도에 들어가면 5단계 튜토리얼이 열립니다. 지도 움직이기, 기업이나 사건 고르기, 영향 경로 보기, 상세와 근거 확인하기, AI에게 질문 순서입니다. 강조된 동작을 마치면 다음 단계로 넘어가고, **튜토리얼 건너뛰기**로 언제든 끝낼 수 있습니다. 시장 전체 지도의 **튜토리얼 다시 보기**로 다시 볼 수 있습니다.

## 메뉴는 어떻게 구성되나요

화면 위쪽 메뉴는 지도, 종목, 브리핑, 내 종목, AI 채팅입니다. 로고(ZOOP)를 누르면 지도로 갑니다.

- **지도**: 첫 화면입니다. 시장 전체 또는 내 종목의 관계 지도를 봅니다.
- **종목**: 기업을 찾고 시세를 보고 관심 종목을 켜고 끕니다.
- **브리핑**: 출근·퇴근 회차의 요약을 읽습니다.
- **내 종목**: 관심 종목과 가상 계좌를 관리합니다. 로그인이 필요합니다.
- **AI 채팅**: AI 질문 창을 엽니다. AI 창은 지도 화면에 있으므로, 다른 화면에서 누르면 지도로 이동한 뒤 열립니다.

오른쪽 위에는 화면 모드 전환과 계정 메뉴가 있습니다. 화면 모드 버튼으로 라이트 모드와 다크 모드를 바꿉니다.

없는 주소로 들어가면 "페이지를 찾을 수 없어요"가 나오고, **지도로 돌아가기**로 돌아올 수 있습니다.

## 지도는 어떻게 읽나요

지도의 원은 기업, 마름모는 사건입니다. 기업 원의 크기는 연결된 사건 수(활동량)를 나타냅니다. 사건은 공시·기사에서 확인된 일이며 여러 기업이 함께 연결될 수 있습니다.

선은 네 가지입니다.

- **직접 관련**: 기업이 사건의 당사자입니다. 계약 당사자나 공시 주체처럼 기사·공시에 행위자로 나옵니다.
- **구조적 관련**: 사건의 당사자는 아니지만 공급망·지분·고객 관계 같은 구조로 영향이 닿는 기업입니다. 관계에 유효 기간이 있을 수 있습니다.
- **후속 사건**: 앞 사건 다음에 이어서 일어난 사건을 잇습니다.
- **사건 공유**: 두 기업이 같은 사건에 연결되어 있을 때 그리는 점선입니다. 두 기업의 관계를 기사가 따로 말한 것은 아니며, 근거는 공유한 사건의 근거를 따릅니다. 영향 경로 계산에는 쓰지 않습니다.

지도 위쪽의 범례는 필터이기도 합니다. 기업, 사건, 직접 관련, 구조적 관련, 후속 사건, 사건 공유를 누르면 그 항목을 숨기거나 다시 보여 주고, 옆의 숫자는 현재 지도의 개수입니다. 기업과 사건을 둘 다 숨길 수는 없습니다.

선이 있다고 해서 주가 영향이나 인과관계를 뜻하지는 않습니다. 관계는 기사에 적힌 사실과 승인된 사업 관계를 나타냅니다.

## 지도는 어떻게 조작하나요

- 이동: 빈 공간을 누른 채 끕니다.
- 확대·축소: 휠을 돌리거나 지도 구석의 확대·축소 버튼을 누릅니다. 전체 그래프 맞춤 버튼은 지도 전체를 화면에 맞춥니다.
- 선택: 기업이나 사건을 누르면 상세 패널이 열리고, 선을 누르면 연결선 상세가 열립니다. 빈 곳을 누르면 선택이 풀립니다. 선택을 닫아도 보고 있던 지도 위치는 그대로입니다.
- 이웃 맞춤: 기업, 사건, 선을 두 번 누르면 연결된 이웃이 보이도록 화면을 맞춥니다.
- 키보드: Tab으로 기업·사건·연결선으로 이동하고, Shift+Enter로 연결된 이웃에 맞출 수 있습니다.
- **기업 중심 그래프**: 기업 패널에서 누르면 그 기업을 중심으로 1단계(직접 이웃까지) 또는 2단계(이웃의 이웃까지)만 남겨 봅니다. **전체 보기**로 돌아옵니다.
- **흐름 순으로 정렬**: 사건에서 관련 기업, 선행 사건에서 후속 사건 방향으로 왼쪽에서 오른쪽으로 정렬합니다. 중심 보기에서는 쓸 수 없습니다.
- **연결 없는 사건**: 현재 지도에서 연결선이 없는 사건을 따로 모아 봅니다. 전체 데이터에 관계가 없다는 뜻은 아닙니다.

휴대전화에서는 빈 곳을 끌어 이동하고 두 손가락으로 확대·축소합니다. 상세 내용은 아래에서 올라오는 시트로 열리며 크기를 조절할 수 있습니다.

지도는 조회 상한에 따라 일부만 표시될 수 있습니다. 그때는 "조회 상한으로 그래프 일부만 표시됩니다"라고 알려 줍니다.

## 내 종목만 지도로 보려면

지도 위쪽의 그래프 모드에서 **내 종목**을 누르면 관심·보유 종목과 연결된 부분만 남습니다. **시장 전체**를 누르면 전체 지도로 돌아옵니다. 로그인하지 않았다면 내 종목 지도를 쓸 수 없고, 로그인 안내와 함께 시장 전체 지도가 유지됩니다.

내 종목 지도에서는 범위를 **전체**, **보유**, **관심** 중에서 고릅니다. 왼쪽의 내 종목 목록에서 보유·관심 종목을 보고, 종목을 눌러 지도에서 찾거나 관심 종목을 켜고 끌 수 있습니다.

내 종목 지도가 비어 있으면 이유와 다음 행동을 알려 줍니다.

- 보유·관심 종목이 없으면 **가상 계좌 연결하기**나 **관심 종목 고르기**를 안내합니다.
- 종목은 있지만 연결된 사건이 없으면 그렇게 표시합니다.
- 범위를 바꾸거나 **시장 전체 지도 보기**로 나갈 수 있습니다.

모드를 바꿔도 각 모드에서 보던 위치와 선택은 기억합니다. 시장 전체 지도 조회에는 개인 정보가 포함되지 않습니다.

## 기업·사건·관계의 상세는 무엇을 보여 주나요

기업 패널은 시세와 최근 1개월 가격 추이, 거래량, 일중 범위, 52주 범위, 주요 지표를 보여 줍니다. 가상 계좌에 있으면 모의 보유 내역도 표시합니다. 그 아래에 직접 관련 사건, 간접 관련 사건, 관련 기업, 뉴스·공시가 있습니다. 위쪽 버튼으로 기업 상세, 관심 추가, 기업 중심 그래프, AI에게 질문을 쓸 수 있습니다.

사건 패널은 핵심 내용, 참여 기업과 역할, 보도 기사와 배경 자료, 앞뒤로 이어진 사건을 보여 줍니다. 근거 건수 버튼으로 근거 문서를 열고, 이슈 중심 그래프와 AI에게 묻기를 쓸 수 있습니다. 확인된 근거가 없으면 요약을 제공하지 않습니다.

연결선 상세는 연결된 두 대상, 관계 종류, 방향, 연결 사건, 관계 기준 문서를 보여 줍니다. 근거에는 발생·보도 언급·계획·전망 같은 보도 표현과 인용 검증 상태가 붙습니다. 구조적 관련 선은 사업 범위, 제품 범위, 유효 기간(예정·유효·종료)을 함께 보여 줍니다. 연결된 근거가 없으면 근거를 추정해 표시하지 않습니다.

패널의 일부만 불러오지 못하면 그 부분에만 오류를 표시하고, 지도는 그대로 유지됩니다.

## 영향 경로와 두 기업 사이 경로는 무엇인가요

영향 경로는 한 기업이 특정 사건과 어떻게 이어지는지 보여 줍니다. 기업 패널의 관련 사건을 누르면 열립니다. 패널 위쪽의 상태는 연결을 어떻게 확인했는지 알려 줍니다.

- **직접 연결 확인**: 기업이 사건에 직접 연결됩니다.
- **구조 관계 확인**: 사업 관계로 연결됩니다. 단계별 근거는 아래 사업 관계 상세에서 봅니다.
- **직접 연결 미확인**: 선택한 그래프에서 직접 연결을 확인하지 못했습니다.

영향 경로 패널에서 근거 건수 버튼, 사건 상세 보기, AI에게 묻기를 쓸 수 있습니다. 이 연결은 기사에 적힌 사실과 승인된 사업 관계이며 주가나 실적 영향을 판단하지 않습니다. 계획·전망 표현은 실제 발생이 확인된 사건과 구분해서 봐야 합니다.

두 기업 사이 경로는 두 기업이 몇 단계로 이어지는지 지도에 표시합니다. 조회된 그래프에서 사건 공유 선을 제외하고, 방향과 관계없이 가장 적은 단계의 연결을 찾습니다. 경로 패널에서 다른 기업을 고를 수 있고 단계마다 근거를 볼 수 있습니다. 최단 연결일 뿐 영향이나 인과관계를 뜻하지 않습니다.

경로는 AI 답변의 **경로 보기**로 엽니다. 지도 화면에서 바로 시작하는 버튼은 없습니다.

## 근거는 어떻게 확인하나요

지도와 패널의 근거 건수 버튼을 누르면 근거 문서 창이 열립니다. 창에는 근거마다 출처, 발행 시각, 문서 제목, 인용 구간이 나옵니다.

인용 구간의 검증 상태는 세 가지입니다.

- **원문 구간 확인됨**: 저장된 원문과 인용이 일치합니다.
- **원문 구간 불일치**: 원문과 인용이 맞지 않습니다.
- **원문 구간 검증 상태 미제공**: 검증 결과가 없습니다.

**원문 보기**는 새 창으로 원문을 엽니다. 원문 링크가 없는 자료도 있습니다. AI 문서 요약이 함께 표시될 수 있지만 원문을 대체하지 않습니다.

**지도에서 보기**를 누르면 그 근거와 연결된 선이나 사건을 지도에서 강조합니다. 연결된 대상이 지금 지도에 없으면 그렇게 알려 줍니다.

문서 발행 시각과 관계 확인 시점은 서로 다릅니다. 앞은 기사가 나온 때이고, 뒤는 관계 근거에 기록된 검증 시각입니다.

근거를 표시할 수 없을 때는 이유를 구분합니다. 권한 없음, 제공 불가(삭제·비공개 또는 이용 권한 변경), 조회 실패입니다. 근거가 충분하지 않으면 원문 인용을 표시하지 않습니다.

## 종목을 찾고 관심 종목을 관리하려면

종목 메뉴에서 기업명, 영문명, 티커, 종목 코드로 검색합니다. 예: 삼성, NVIDIA, 005930. 목록의 범위는 **시장 전체**와 **내 종목**이고, 내 종목에서는 전체·보유·관심으로 좁힙니다.

목록의 각 행에서 다음을 할 수 있습니다.

- 시세와 승인된 사건 수를 봅니다.
- 기업 이름을 눌러 기업 상세로 갑니다.
- 지도에서 보기로 그 기업을 지도에서 찾습니다.
- 별 표시(☆/★)로 관심 종목을 켜고 끕니다.

보유 종목에는 보유 표시가 붙습니다. 목록 끝의 **더 보기**로 다음 종목을 불러옵니다.

관심 종목은 세 곳에서 바꿀 수 있습니다. 종목 메뉴의 별 표시, 지도 기업 패널의 관심 추가 버튼, 내 종목 화면의 **관심 추가**입니다. 비회원이 기업 패널을 보면 **로그인 후 관심 추가**가 나옵니다.

저장에 실패하면 이전 상태로 되돌리고 알려 줍니다. 관심 종목 저장은 내 종목 지도와 브리핑의 내 종목 기준에 함께 반영됩니다.

## 기업 상세에서 무엇을 볼 수 있나요

기업 상세는 왼쪽에 기업 목록, 가운데에 기업 정보, 오른쪽에 관계 그래프가 있습니다.

왼쪽 목록에서 검색 결과, 보유 기업, 관심 기업, 최근 본 기업, 연결된 기업을 오갈 수 있습니다.

가운데 영역에는 기업 개요, 최신 제공 시세(시가총액, 거래량, 당일 및 52주 범위), 주요 지표, 가상 계좌 보유 정보가 있습니다. 시세 차트는 기간을 1일, 1주, 1개월, 1년 중에서 고르며 기본은 1개월입니다. **표로 보기**를 쓸 수 있습니다.

탭은 세 가지입니다.

- **사건**: 시점별 사건 타임라인과 선택 사건의 내용을 봅니다.
- **문서**: 뉴스·공시를 전체, 뉴스, 공시로 나눠 보고, 문서별 인용과 긍정·부정 판정을 봅니다.
- **기업 정보**: 정식 법인명, 시장, 업종, 대표자, 설립일, 홈페이지와 핵심 재무를 봅니다.

오른쪽 **관계 그래프**는 1단계, 2단계 깊이를 고르고 **지도에서 보기**로 큰 지도로 옮겨 갑니다. 사건의 **이 당시 관계그래프 보기**를 누르면 그 사건 시점의 관계를 보여 주고, **현재 시점으로** 돌아올 수 있습니다.

차트와 사건의 시점이 겹쳐도 인과관계를 뜻하지 않습니다. 과거 기준 시점으로 보는 중이면 **최신 시점**으로 돌아갈 수 있습니다.

## 브리핑은 어떻게 보나요

브리핑은 출근·퇴근 회차마다 발행되는 시장 요약입니다. 브리핑 메뉴를 열면 최신 회차가 나옵니다.

회차 선택: 날짜와 출근·퇴근을 고릅니다. 발행되지 않은 회차에는 미발행, 제공이 끊긴 회차에는 중단이 표시됩니다. **이전 회차 더 보기**로 지난 회차를 불러옵니다.

브리핑 기준: **공통**은 모두에게 같은 내용이고, **내 종목 기준**은 보유·관심 종목의 관련 이슈를 함께 보여 줍니다. 내 종목 기준에는 로그인과 내 종목 설정이 필요합니다.

읽기 방식: **간단히**는 핵심 위주이고 **전체 보기**는 전체 분석과 보존 자료까지 보여 줍니다. 기본은 간단히입니다.

브리핑의 주요 구성은 다음과 같습니다.

- 시장 요약과 오늘의 전망, 주요 시장 지표
- 핵심 이슈: 순위, 제목, 근거 건수, 선정 이유, 관련 기업
- 핵심 이슈 기업별 전망과 회차 기준 시세
- 이전 브리핑과 핵심 이슈 변화: 신규, 이어짐, 빠짐
- 이 회차 관계 그래프에서 보기: 회차 기준 지도로 이동

이슈마다 자세히 보기와 근거 보기를 펼쳐 사실·계획·전망 구분과 원문을 확인합니다. 로그인한 회원은 브리핑을 평가할 수 있습니다.

## 브리핑의 전망과 판단은 어떻게 읽나요

브리핑의 전망은 투자 권유가 아닙니다. 사업상 의미를 정리한 것이며 주가 방향을 뜻하지 않습니다.

- 기업 전망: 사업상 긍정 요인, 사업상 부담 요인, 긍정·부담 요인 혼재, 추가 확인 필요로 나타냅니다.
- 시장 전망: 상승 가능성, 하락 가능성, 보합 가능성, 불확실로 나타내고, 이전 전망 대비 유지·강화·완화·철회를 표시합니다.
- 관찰 입장: 우선 관찰, 관찰 유지, 주의해서 관찰, 판단 유보로 나타냅니다. 매수 판단으로 확대하지 않습니다.
- 조건 확인: 조건 관측, 반대 근거 관측, 미관측·평가 유보로 나타냅니다. 조건이 관측되지 않으면 적중이나 실패로 평가하지 않습니다.

퇴근 브리핑은 아침 예상과 실제 결과를 비교합니다. 같은 날 출근 판단이 없으면 비교하지 않습니다.

가격이 움직였다는 사실만으로 뉴스의 영향이나 전망 적중을 단정하지 않습니다. 실제 가격 변동은 사업 전망의 적중이나 이슈의 인과관계를 입증하지 않습니다.

빠짐은 핵심 이슈 선정에서 빠졌다는 뜻이며 악재나 사건의 해소를 뜻하지 않습니다.

새 이슈가 선정되지 않은 회차는 참고, 복기, 확인 브리핑으로 표시됩니다. 시장 전체에 새 소식이 없다는 뜻은 아닙니다. 과거 자료로 만든 회차에는 과거 자료 시뮬레이션이라고 표시합니다.

## 내 종목과 가상 계좌는 어떻게 쓰나요

내 종목 메뉴는 로그인한 회원만 쓸 수 있습니다. 보유 종목과 관심 종목을 한 화면에서 관리합니다.

보유 종목: 연결한 가상 계좌의 모의 보유 종목과 평가 금액을 보여 줍니다. 가상 계좌는 실제 증권 계좌가 아니라 준비된 모의 데이터로 만든 계좌입니다. 실제 돈이나 주문과 관계가 없습니다.

- 연결 전: **가상 계좌 연결하기**로 계좌를 고릅니다. 연결하기 전에 계좌 종류, 예수금, 평가 기준, 보유 종목을 미리 볼 수 있습니다.
- 연결 후: **연결 끊기**로 끊을 수 있습니다. 끊어도 종목은 그대로이고 나중에 다시 연결할 수 있습니다.

관심 종목: 목록에서 승인된 사건 수를 보고, 기업 검색으로 추가하거나 목록에서 뺍니다. 추가한 종목은 내 종목 지도에 함께 보입니다.

각 종목은 지도에서 보기와 기업 상세로 이어집니다.

보유·관심 종목이 모두 없으면 지도는 시장 전체로 열립니다.

## AI에게 어떻게 질문하나요

AI 질문은 로그인한 회원만 쓸 수 있습니다. 위쪽 메뉴의 **AI 채팅**이나 지도 패널의 **AI에게 질문**, **AI에게 묻기**로 창을 엽니다. 패널에서 열면 보고 있던 기업, 사건, 관계, 영향 경로가 질문에 연결됩니다.

질문은 4,000자까지 쓸 수 있습니다. 이렇게 물어볼 수 있습니다.

- 개념: "HBM이 뭐야?"
- 기업과 사건: "SK하이닉스와 엮인 사건 알려줘"
- 관계: "NVIDIA와 SK하이닉스는 어떻게 연결돼 있어?"
- 변화: "10월 5일 이후 지도에서 달라진 관계는?"
- 브리핑: "오늘 출근 브리핑 요약해줘"
- 내 종목: "내 종목 중에 HBM 사건과 연결된 게 있어?"
- 서비스: "탈퇴하면 질문 기록은 어떻게 돼?"

한 번에 여러 가지를 물어도 됩니다. 일부만 답할 수 있으면 답한 부분과 답하지 못한 부분을 나눠 보여 줍니다.

"그 기업"처럼 대상을 가리키면 어떤 대상인지 되물을 수 있습니다. 선택지를 고르거나 직접 입력해 답합니다. 연결한 대상과 다른 대상을 질문에 적으면 질문에 적힌 대상을 기준으로 답하고 그렇게 알려 줍니다.

답변을 만드는 동안에는 진행 단계를 보여 줍니다. 같은 대화에서는 처리가 끝날 때까지 새 질문을 보낼 수 없습니다. **질문 취소**로 취소할 수 있습니다. 창을 닫거나 새로 고쳐도 질문은 서버에서 계속 처리되고, 다시 열면 결과를 볼 수 있습니다.

## AI 답변의 표시는 무엇을 뜻하나요

답변의 구간마다 근거 수준이 표시됩니다.

- **일반 개념**: 개념 설명입니다. 최신 기업·시장 사실은 담지 않습니다.
- **ZOOP 안내**: 줍의 약관 같은 공식 문서를 근거로 한 안내입니다.
- **근거 확인됨**: 공개 기사·공시 등 근거로 확인한 내용입니다.
- **웹 검색 보도**: 웹 검색 결과에 적힌 내용입니다. 줍이 확인한 사실은 아닙니다. 웹 검색이 꺼져 있는 동안에는 이 표시가 나오지 않습니다.

근거가 있는 문장에는 번호가 붙고, 아래 **인용** 목록에서 출처와 인용문을 볼 수 있습니다. 인용은 서버가 실제 조회 결과로 만듭니다.

답변 아래에는 다음이 나올 수 있습니다.

- **답하지 않은 부분**: 답하지 못한 부분과 이유입니다. 조회 범위에서 자료를 찾지 못함, 근거 부족, 답변 내용을 확인하지 못해 뺌, 자료 조회 일시 장애, 범위 밖 등을 구분합니다.
- **참고할 점**: 답에는 지장이 없지만 알아 둘 내용입니다.
- **안내**: 자료 일부를 일시적으로 읽지 못해 확인한 자료로만 답한 경우처럼 답이 만들어진 상황을 알려 줍니다.
- **적용 범위**: 답변 기준이 된 기업, 사건, 기간입니다.
- 바로가기: 지도에서 보기, 기업 상세, 경로 보기, 관계 보기, 근거 보기, 브리핑 열기, 내 종목 보기입니다. 누를 때만 동작합니다. 답변을 만든 그래프와 지금 지도의 기준이 다르면 열 수 없다고 알려 줍니다.

근거가 부족하면 지어내지 않고 답하지 않은 이유를 알려 줍니다. 검증을 마친 답변만 보여 드립니다.

## AI 대화 기록은 어떻게 관리하나요

AI 창의 **대화 기록**에서 지난 대화를 보고 다시 열 수 있습니다. 목록 끝의 **더 보기**로 이전 대화를 더 불러옵니다. **새 대화**를 누르면 새로 시작합니다. 대화 기록은 서버에 저장되어 있어 다시 열어도 답변을 새로 만들지 않습니다.

대화를 하나씩 지우는 기능은 지금 제공하지 않습니다. 회원 탈퇴 시 운영자가 보관한 대화 기록은 파기됩니다. 법령상 별도 보존이 필요한 정보와 외부 AI 제공자의 기록은 개인정보 처리방침을 따릅니다.

질문에 문제가 생기면 카드에 상태와 할 수 있는 일이 나옵니다.

- **질문 다시 처리**: 다시 물어도 되는 실패일 때만 나옵니다.
