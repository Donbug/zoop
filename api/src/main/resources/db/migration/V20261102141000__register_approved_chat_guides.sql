- 주요 동작: **기업 상세**(`/companies/:id`로 이동), 관심 추가와 관심 해제, **기업 중심 그래프**(D-GRP-07b), **AI에게 질문**입니다. 비회원에게는 **로그인 후 관심 추가**가 나옵니다.
- 시세 영역: 거래량, 일중 범위, 52주 범위, 최근 1개월 시세 추이입니다.
- **주요 지표**: 접고 펼치는 목록입니다.
- **가상 계좌 보유**: 수량 등 모의 보유 내역입니다.
- **직접 관련 사건**, **간접 관련 사건**: 누르면 D-GRP-06 영향 경로가 열립니다.
- **관련 기업**: 누르면 그 기업으로 옮겨 갑니다.
- **뉴스·공시**: 제목, 종류, 출처, 시각입니다.

상태별 표시: 영역마다 따로 불러오므로 일부가 실패해도 나머지는 보입니다. 시세가 없으면 시세 미제공과 이유를 표시합니다. 관심 저장에 실패하면 "관심기업 저장에 실패했습니다"와 **재시도**가 나옵니다. 사건, 기업, 문서가 없으면 각각 없다고 구분해 표시합니다.

## D-GRP-04 연결선 상세

두 점을 잇는 선을 눌렀을 때 열립니다.

구성 요소:

- **연결된 두 대상**: 양쪽 기업·사건과 닫기 버튼입니다.
- **관계 정보**: 관계 종류(직접 관련, 구조적 관련, 후속 관계, 사건 공유), 방향, 역할입니다.
- **연결 사건**, **공유 사건**: 이 관계가 기대는 사건 목록입니다. 사건 공유 선에서는 함께 언급된 사건을 보여 줍니다.
- **관계 기준 문서**: 관계를 뒷받침하는 문서입니다. 확인 시점, 검증 상태, 보도 표현(발생, 보도 언급, 계획, 전망), 인용 검증(통과, 확인 필요, 해당 없음)을 함께 표시합니다.
- **사업 관계 상세**: 구조적 관련 선에서 사업 범위, 제품 범위, 유효 기간, 상태(예정, 유효, 종료, 미상), 관계 확인 시각을 보여 줍니다.
- 근거 버튼: D-GRP-05를 엽니다. **AI에게 묻기**는 이 연결선을 질문 대상으로 연결합니다.

사업 관계 상세에는 사건의 직접 참여나 주가 영향을 뜻하지 않는다는 안내가 있습니다.

상태별 표시: 연결된 근거가 없으면 "연결된 근거가 없습니다. 근거를 추정해 표시하지 않습니다"라고 표시합니다. 불러오지 못하면 지도는 유지하고 **다시 시도**를 줍니다.

## D-GRP-05 근거 문서 창

지도, 패널, AI 답변의 근거 버튼으로 여는 창입니다. 창이 열리면 뒤쪽 화면은 조작할 수 없고, 닫으면 보던 화면으로 돌아옵니다.

구성 요소:

- **선택한 연결의 근거**: 무엇의 근거인지와 관계 확인 시점입니다. 관계 확인 시점은 그래프 조회 기준이나 문서 발행 시각과 다릅니다.
- 근거 카드: 출처(언론사와 도메인), 발행 시각, 검증 표시, 문서 제목, 인용문입니다.
- 원문 구간 표시: 확인됨, 불일치, 검증 상태 미제공입니다.
- 원문 보기: 새 창으로 엽니다. 링크가 없으면 그렇게 표시합니다.
- **AI 문서 요약**: 문서 요약과 해석, 한계, 기업별 판정입니다. 원문을 대체하지 않습니다.
- **◇ 지도에서 보기**: 근거와 연결된 선이나 사건을 강조합니다. 강조 중에는 지도가 어두워지지 않아 창 옆에서 볼 수 있습니다. 다시 누르면 강조를 끕니다.

상태별 표시:

- 불러오는 중: "근거 문서를 불러오는 중입니다"
- 근거 없음: "연결된 근거가 없습니다"
- 근거 부족: "근거가 충분하지 않아 원문 인용을 표시하지 않습니다"
- 일부 실패: "일부 근거를 불러오지 못했습니다"와 이유(권한 없음, 제공 불가, 조회 실패), **다시 시도**
- 지도에 대상 없음: "이 근거와 연결된 선이나 사건이 지금 지도에 없어요"

## D-GRP-06 기업에서 여는 영향 경로

기업 패널의 관련 사건을 누르면 열립니다. 기업과 사건을 잇는 경로를 지도에 강조합니다.

구성 요소:

- 연결 상태 표시: 연결 확인 중, 연결 확인, 직접 연결 확인, 구조 관계 확인, 직접 연결 미확인, 연결 확인 불가입니다.
- **공개 그래프 연결**: 그래프에서 확인된 연결입니다.
- **확인된 연결**: 함께 연결된 다른 기업입니다.
- **사업 관계 상세**: 구조 관계의 범위와 유효 기간입니다.
- 근거 건수 버튼: D-GRP-05를 엽니다.
- **사건 상세 보기**: D-GRP-02로 이동합니다.
- **AI에게 묻기**: 영향 경로를 질문 대상으로 연결합니다.
- **해석 한계**: 기사에 적힌 사실과 승인된 사업 관계이며 주가나 실적 영향을 판단하지 않는다는 안내입니다.

상태별 표시: 현재 공개 권한을 확인할 수 있는 근거만 표시합니다. 불러오지 못해도 "지도와 기업 선택은 그대로 유지됩니다"라고 알리고 **다시 시도**를 줍니다. 선택한 그래프 버전에서 상세를 찾지 못하면 기업과 이슈를 다시 선택하게 합니다.

휴대전화에서는 **경로 단계 보기**, **지도로 접기**, **경로 나가기**로 패널과 지도를 오갑니다.

## D-GRP-07·D-GRP-07b 두 기업 경로·포커스

D-GRP-07 두 기업 사이 경로: 두 기업을 잇는 최단 연결을 지도에 표시합니다. AI 답변의 **경로 보기**로 열 수 있습니다.

- 머리 부분: 두 기업 이름과 경로 닫기 버튼입니다. 지도 위에는 단계 수가 표시됩니다.
- **두 번째 기업 선택**: 기업 검색으로 비교 기업을 고르거나 **다른 기업 고르기**로 바꿉니다.
- 경로 단계 목록: 기업과 사건을 차례로 보여 주고 근거 건수를 표시합니다. 항목을 누르면 그 대상으로 옮겨 갑니다.
- **근거 보기**: D-GRP-05를 엽니다.
- **경로를 찾는 방법**: 사건 공유 선을 제외하고 방향과 관계없이 가장 적은 단계의 연결을 찾는다는 설명입니다. 영향이나 인과관계를 뜻하지 않습니다.

상태별 표시: 비교 기업이 조회 범위에 없으면 다른 기업을 고르게 합니다. 경로가 없으면 "조회한 그래프 안에서 두 기업 사이 경로를 찾지 못했어요"라고 표시합니다. 조회 상한에 걸리면 일부 관계가 생략됐다고 알립니다.

지도 화면에는 이 경로를 바로 시작하는 버튼이 없습니다.

D-GRP-07b 선택 기업 포커스: 한 기업이나 사건을 중심으로 가까운 연결만 남겨 봅니다. 기업 패널의 **기업 중심 그래프**, 사건 패널의 **이슈 중심 그래프**로 들어갑니다.

- 단계 선택: 1단계는 직접 이웃까지, 2단계는 이웃의 이웃까지입니다.
- **전체 보기**: 포커스를 끝내고 전체 지도로 돌아옵니다.

포커스 중에는 흐름 순 정렬을 쓸 수 없습니다.

## D-STK-01 종목 탐색

종목 메뉴(`/stocks`)입니다. 비회원도 쓸 수 있습니다.

구성 요소:

- **종목 검색**: 기업명, 영문명, 티커로 찾습니다. 예시는 삼성, NVIDIA, 005930이고 검색어 지우기가 있습니다.
- 종목 범위: **시장 전체**, **내 종목**입니다. 내 종목에서는 **전체**, **보유**, **관심** 필터가 나옵니다.
- 종목 목록: 행마다 기업 로고와 이름, 보유 표시, 시세, 승인 사건 수가 있습니다. 시세는 행별로 불러옵니다.
- 행 동작: 기업 상세, 지도에서 보기, 관심 종목 별 표시입니다.
- **더 보기**: 다음 종목을 불러옵니다.

상태별 표시:

- 검색 결과 없음: 검색어와 함께 결과가 없다고 표시합니다.
- 내 종목 없음: "보유·관심 종목이 없어요. 시장 전체에서 ☆로 관심 종목을 추가해 보세요."
- 필터 결과 없음: "표시할 보유 종목이 없어요", "표시할 관심 종목이 없어요"
- 불러오기 실패: 목록을 빈 것으로 표시하지 않고 다시 불러올 수 있습니다.
- 시세: 시세 불러오는 중, 시세 확인 실패, 시세 없음을 구분합니다.
- 관심 저장 실패: 그 종목을 이전 상태로 되돌리고 알립니다.

## D-COM-01·D-COM-05·D-COM-06 기업 상세·차트

주소는 `/companies/:id`입니다. 왼쪽 기업 목록, 가운데 내용, 오른쪽 관계 그래프의 세 영역입니다.

왼쪽 **기업 선택**: 기업 검색과 검색 결과, 보유 기업, 관심 기업, 최근 본 기업, 연결된 기업 묶음입니다. 보유·관심은 로그인 후 볼 수 있습니다.

**기업 개요**: 이름, 코드, 시장, 업종, 요약, 보유·관심 표시입니다.

**최신 제공 시세**: 시세, 기준 시각, 지연 정보, 시가총액, 거래량, 당일 저가~고가, 52주 저가~고가입니다.

주요 지표: 최신 기준의 기업 지표 목록입니다.

가상 계좌 보유: 프로젝트용 모의 데이터입니다. 보유 수량, 평균 매입가, 평가 금액, 자산 비중을 보여 줍니다.

시세 차트: 기간은 1일(5분), 1주(1시간), 1개월(일), 1년(주)이며 기본은 1개월입니다. 차트에 사건이 표시되고, **표로 보기**로 시각과 종가를 표로 봅니다. **최신 시점**은 과거 기준 시점에서 돌아옵니다. 차트와 사건의 시점이 겹쳐도 인과관계를 뜻하지 않습니다.

기준 시점 보기: 그래프 버전이 처음 공개된 시점으로 볼 때는 그렇게 표시합니다. 그 시점의 공개 자료가 없으면 최신 시점으로 돌아가도록 안내합니다.

없는 기업이면 "기업을 찾을 수 없어요"와 **시장 전체 지도에서 찾기**, **내 종목 보기**가 나옵니다.

## D-COM-02 기업 상세의 탭과 관계 그래프

기업 상세 가운데의 탭입니다. **사건**, **문서**, **기업 정보**가 있습니다.

사건 탭(D-COM-01b): 사건 타임라인을 시점 묶음별로 보여 줍니다. 사건마다 관계(직접 관련, 구조적 관련)와 시점이 있습니다.

- 사건을 고르면 선택 사건의 내용과 영향 경로가 나옵니다.
- **이 당시 관계그래프 보기**: 오른쪽 그래프를 사건 시점 기준으로 바꿉니다.
- **이 사건 시점의 관계를 지도에서 보기**: 큰 지도로 이동합니다.

문서 탭(D-COM-02): 뉴스·공시 목록입니다.

- 문서 종류: 전체, 뉴스, 공시입니다.
- **전체 기업 문서**와 **선택 사건의 근거** 범위를 오갑니다.
- 문서마다 제목, 종류, 출처, 발행 시각, 사건을 보도한 자료·배경 자료 구분, 긍정·부정·혼재·판단 보류 판정이 있습니다.
- 문서를 고르면 인용(확인됨, 불일치, 미확인), 원문 보기, 문서 요약이 나옵니다.
- 선택 시점 이후에 발행된 문서는 표시하지 않습니다.

기업 정보 탭: 기업 기준정보(정식 법인명, 시장, 업종, 대표자, 설립일, 홈페이지)와 핵심 재무입니다.

오른쪽 관계 그래프(D-COM-04): 기준 시점의 기업 관계를 작은 그래프로 보여 줍니다. 1단계, 2단계로 깊이를 고르고, 확대·축소하고, **지도에서 보기**로 이동합니다. 사건 시점으로 보는 중이면 **현재 시점으로** 돌아갑니다. ○는 기업, ◆는 사건, 점선은 파생 관계입니다.

## D-BRF-01·D-BRF-02 출근·퇴근 브리핑

주소는 `/briefing`이며 날짜와 회차가 주소에 남습니다. 비회원도 공통 브리핑을 볼 수 있습니다.

조작 영역:

- 회차 선택: 날짜와 출근·퇴근입니다. 미발행, 중단 표시와 **이전 회차 더 보기**가 있습니다.
- 브리핑 기준: **공통**, **내 종목 기준**입니다.
- 읽기 방식: **간단히**(기본), **전체 보기**입니다.

본문:

- 회차 표시: 발행, 발행 전, 생성 중, 생성 실패, 발행 중단 상태와 참고·복기·확인 브리핑 표시입니다.
- **시장 요약**: 핵심 먼저 읽기, 오늘의 전망 또는 다음 거래일의 전망입니다.
- **주요 시장 지표**: 지표별 값, 등락, 기준, 상태(지연, 사용 불가, 조회 실패)입니다.
