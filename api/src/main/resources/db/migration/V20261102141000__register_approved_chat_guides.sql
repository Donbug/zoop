- 3단계(D-GRP-T3) **영향 경로 보기**: 강조된 사건이나 기업 상세의 같은 사건을 누르면 영향 경로가 열립니다. 점선인 사건 공유 연결은 경로 계산에 쓰지 않습니다.
- 4단계(D-GRP-T4) **상세와 근거 확인하기**: 영향 경로의 근거 버튼으로 기사·공시를 확인합니다. 문서 발행 시각과 관계 확인 시각은 다를 수 있습니다.
- 5단계(D-GRP-T5) **AI에게 질문**: 강조된 버튼을 누르면 AI 창을 열지 않고 튜토리얼을 마칩니다.

공통 버튼은 **이전**, **다음**, **마치기**, **튜토리얼 건너뛰기**입니다. 지도를 불러오지 못하면 **다시 시도**나 건너뛰기를 안내합니다. 튜토리얼을 다시 보려면 시장 전체 지도의 **튜토리얼 다시 보기**를 누릅니다.

