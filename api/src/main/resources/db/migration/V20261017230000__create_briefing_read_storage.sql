-- ERD v6 sections 19 and 21: immutable briefing originals and append-only changes, read by the public API.
-- This migration is additive. It never replaces the document owner's artifacts/articles/evidence registries.
-- graph_versions and admins are not installed by their owners yet. Their real FKs are follow-up migrations;
-- no stand-in graph/admin tables or graph-ready/rights-approved values are created here.
-- No publication/admin/generation HTTP writer is installed. Active generation requires the future attempts owner.

CREATE TABLE briefing_rounds (
    id text PRIMARY KEY CHECK (btrim(id) <> ''),
    round_date date NOT NULL,
    edition text NOT NULL CHECK (edition IN ('morning', 'evening')),
    scheduled_at timestamptz NOT NULL,
    window_from timestamptz,
    window_to timestamptz NOT NULL,
    open_start boolean NOT NULL,
    status text NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'missing', 'generating', 'verifying', 'published', 'failed', 'suspended')),
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    stages jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(stages) = 'object'),
    failure_reason text,
    attempt_no integer NOT NULL DEFAULT 0 CHECK (attempt_no >= 0),
    generation_token text CHECK (generation_token IS NULL OR btrim(generation_token) <> ''),
    lease_until timestamptz,
    graph_version_id text CHECK (graph_version_id IS NULL OR btrim(graph_version_id) <> ''),
    review_revision bigint CHECK (review_revision >= 0),
    rule_revision bigint CHECK (rule_revision >= 0),
    published_payload jsonb CHECK (published_payload IS NULL OR jsonb_typeof(published_payload) = 'object'),
    public_snapshot jsonb CHECK (public_snapshot IS NULL OR jsonb_typeof(public_snapshot) = 'object'),
    schema_version text CHECK (schema_version IS NULL OR btrim(schema_version) <> ''),
    -- SHA-256 of convert_to(published_payload::text,'UTF8'), PostgreSQL's JSONB text representation.
    -- This is not a hash of the producer's original/canonical JSON bytes.
    payload_sha256 text CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    morning_round_id text REFERENCES briefing_rounds(id) ON DELETE RESTRICT,
    comparison_snapshot jsonb CHECK (comparison_snapshot IS NULL OR jsonb_typeof(comparison_snapshot) = 'object'),
    generated_at timestamptz,
    published_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (round_date, edition),
    CHECK (open_start = (window_from IS NULL)),
    CHECK (window_from IS NULL OR window_from < window_to),
    CHECK (morning_round_id IS NULL OR (edition = 'evening' AND morning_round_id <> id)),
    CHECK ((status IN ('generating', 'verifying') AND generation_token IS NOT NULL AND lease_until IS NOT NULL)
        OR (status NOT IN ('generating', 'verifying') AND generation_token IS NULL AND lease_until IS NULL)),
    CHECK ((status IN ('published', 'suspended')) = (published_at IS NOT NULL)),
    CHECK (published_at IS NULL OR (review_revision IS NOT NULL AND published_payload IS NOT NULL
        AND public_snapshot IS NOT NULL AND generated_at IS NOT NULL AND schema_version IS NOT NULL
        AND payload_sha256 IS NOT NULL)),
    CHECK (published_at IS NULL OR generated_at <= published_at)
);

CREATE INDEX briefing_rounds_history_idx ON briefing_rounds (round_date DESC, edition, id);
CREATE INDEX briefing_rounds_schedule_idx ON briefing_rounds (status, scheduled_at);
CREATE INDEX briefing_rounds_public_cursor_idx ON briefing_rounds (scheduled_at DESC, id COLLATE "C" DESC)
    WHERE published_at IS NOT NULL;

CREATE TABLE briefing_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id text NOT NULL REFERENCES briefing_rounds(id) ON DELETE RESTRICT,
    kind text NOT NULL CHECK (kind IN ('correction', 'suspension')),
    seq integer NOT NULL CHECK (seq > 0),
    event_id text CHECK (event_id IS NULL OR btrim(event_id) <> ''),
    original text,
    corrected text,
    suspended boolean,
    reason text NOT NULL CHECK (btrim(reason) <> ''),
    admin_id text NOT NULL CHECK (btrim(admin_id) <> ''),
    admin_email_snapshot text NOT NULL CHECK (btrim(admin_email_snapshot) <> ''),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (round_id, kind, seq),
    CHECK ((kind = 'correction' AND corrected IS NOT NULL AND btrim(corrected) <> '' AND suspended IS NULL)
        OR (kind = 'suspension' AND suspended IS NOT NULL AND corrected IS NULL
            AND event_id IS NULL AND original IS NULL))
);
CREATE INDEX briefing_changes_round_idx ON briefing_changes (round_id, id);

-- A small structural predicate used below; it also rejects duplicate identifiers and blank strings.
CREATE FUNCTION briefing_read_identifier_array(value jsonb) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN jsonb_typeof(value) = 'array' THEN
        NOT EXISTS (SELECT 1 FROM jsonb_array_elements(value) AS e
            WHERE jsonb_typeof(e) <> 'string' OR btrim(e #>> '{}') = '')
        AND (SELECT count(DISTINCT e #>> '{}') FROM jsonb_array_elements(value) AS e) = jsonb_array_length(value)
    ELSE false END
$$;

CREATE FUNCTION protect_briefing_read_round() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    p jsonb; item jsonb; refs jsonb; binding jsonb; reference_id text; binding_count integer;
    item_count integer; morning briefing_rounds;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.published_at IS NOT NULL THEN RAISE EXCEPTION 'published briefing is immutable'; END IF;
        RETURN OLD;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF ROW(NEW.id, NEW.round_date, NEW.edition, NEW.scheduled_at, NEW.window_from, NEW.window_to,
               NEW.open_start, NEW.created_at)
           IS DISTINCT FROM ROW(OLD.id, OLD.round_date, OLD.edition, OLD.scheduled_at, OLD.window_from,
               OLD.window_to, OLD.open_start, OLD.created_at)
        THEN RAISE EXCEPTION 'briefing identity and input window are immutable'; END IF;
        IF NEW.revision < OLD.revision THEN RAISE EXCEPTION 'briefing revision cannot decrease'; END IF;
        IF OLD.published_at IS NOT NULL AND
            (to_jsonb(NEW) - ARRAY['status', 'revision']) IS DISTINCT FROM
            (to_jsonb(OLD) - ARRAY['status', 'revision'])
        THEN RAISE EXCEPTION 'published briefing is immutable'; END IF;
        IF OLD.published_at IS NOT NULL AND NEW.status IS DISTINCT FROM OLD.status AND NEW.revision <= OLD.revision
        THEN RAISE EXCEPTION 'briefing status change must increase revision'; END IF;
    END IF;
    IF NEW.published_at IS NOT NULL AND (TG_OP = 'INSERT' OR OLD.published_at IS NULL) THEN
        p := NEW.published_payload;
        IF p IS NULL OR jsonb_typeof(p) IS DISTINCT FROM 'object'
            OR NOT (p ?& ARRAY['id', 'date', 'edition', 'scheduledAt', 'generatedAt', 'dataWindow', 'graphVersion',
                'reviewRevision', 'ruleRevision', 'items', 'references', 'emptyReason', 'selectedFrom',
                'marketVariables', 'metadata', 'outlook'])
            OR jsonb_typeof(p->'items') IS DISTINCT FROM 'array'
            OR jsonb_typeof(NEW.public_snapshot) IS DISTINCT FROM 'object'
            OR NOT (NEW.public_snapshot ?& ARRAY['marketSummary', 'sourceBindings'])
            OR jsonb_typeof(p->'metadata') IS DISTINCT FROM 'object'
            OR jsonb_typeof(p->'dataWindow') IS DISTINCT FROM 'object'
            OR NOT ((p->'dataWindow') ?& ARRAY['start', 'end', 'openStart'])
            OR jsonb_typeof(p->'reviewRevision') IS DISTINCT FROM 'number'
            OR p->>'id' IS DISTINCT FROM NEW.id OR p->>'date' IS DISTINCT FROM NEW.round_date::text
            OR p->>'edition' IS DISTINCT FROM NEW.edition
            OR p->>'graphVersion' IS DISTINCT FROM NEW.graph_version_id
            OR p->>'reviewRevision' IS DISTINCT FROM NEW.review_revision::text
            OR p->>'ruleRevision' IS DISTINCT FROM NEW.rule_revision::text
            OR (p->>'scheduledAt')::timestamptz IS DISTINCT FROM NEW.scheduled_at
            OR (p->>'generatedAt')::timestamptz IS DISTINCT FROM NEW.generated_at
            OR (p->'dataWindow'->>'start')::timestamptz IS DISTINCT FROM NEW.window_from
            OR (p->'dataWindow'->>'end')::timestamptz IS DISTINCT FROM NEW.window_to
            OR (p->'dataWindow'->>'openStart')::boolean IS DISTINCT FROM NEW.open_start
            OR NEW.payload_sha256 IS DISTINCT FROM encode(sha256(convert_to(p::text, 'UTF8')), 'hex')
        THEN RAISE EXCEPTION 'invalid published briefing identity or digest'; END IF;
        IF (NEW.graph_version_id IS NOT NULL AND jsonb_typeof(p->'graphVersion') IS DISTINCT FROM 'string')
            OR (NEW.graph_version_id IS NULL AND p->'graphVersion' IS DISTINCT FROM 'null'::jsonb)
            OR (NEW.rule_revision IS NOT NULL AND jsonb_typeof(p->'ruleRevision') IS DISTINCT FROM 'number')
            OR (NEW.rule_revision IS NULL AND p->'ruleRevision' IS DISTINCT FROM 'null'::jsonb)
            OR jsonb_typeof(p->'dataWindow'->'openStart') IS DISTINCT FROM 'boolean'
        THEN RAISE EXCEPTION 'invalid published briefing nullable version or window'; END IF;
        item_count := jsonb_array_length(p->'items');
        IF item_count > 3 THEN RAISE EXCEPTION 'briefing items exceed three'; END IF;
        IF (item_count = 0 AND p->>'emptyReason' IS DISTINCT FROM 'no_issues_in_window')
            OR (item_count > 0 AND p->'emptyReason' IS DISTINCT FROM 'null'::jsonb)
        THEN RAISE EXCEPTION 'briefing empty reason must agree with its items'; END IF;
        refs := p->'references';
        IF jsonb_typeof(refs) IS DISTINCT FROM 'object'
            OR NOT briefing_read_identifier_array(refs->'eventIds')
            OR NOT briefing_read_identifier_array(refs->'evidenceIds')
            OR NOT briefing_read_identifier_array(refs->'companyIds')
        THEN RAISE EXCEPTION 'invalid briefing references'; END IF;
        FOR item IN SELECT value FROM jsonb_array_elements(p->'items') LOOP
            IF jsonb_typeof(item) IS DISTINCT FROM 'object'
                OR jsonb_typeof(item->'eventId') IS DISTINCT FROM 'string' OR btrim(item->>'eventId') = ''
                OR jsonb_typeof(item->'rank') IS DISTINCT FROM 'number' OR item->>'rank' NOT IN ('1', '2', '3')
                OR NOT briefing_read_identifier_array(item->'evidenceIds')
                OR jsonb_array_length(item->'evidenceIds') = 0
                OR NOT ((refs->'evidenceIds') @> (item->'evidenceIds'))
                OR NOT (refs->'eventIds' @> jsonb_build_array(item->>'eventId'))
            THEN RAISE EXCEPTION 'invalid briefing item identity, rank or evidence reference'; END IF;
        END LOOP;
        IF (SELECT count(DISTINCT value->>'eventId') FROM jsonb_array_elements(p->'items')) <> item_count
            OR (SELECT count(DISTINCT value->>'rank') FROM jsonb_array_elements(p->'items')) <> item_count
            OR jsonb_array_length(refs->'eventIds') <> item_count
        THEN RAISE EXCEPTION 'duplicate or unmatched briefing item references'; END IF;
        FOR reference_id IN SELECT jsonb_array_elements_text(refs->'companyIds') LOOP
            IF NOT EXISTS (SELECT 1 FROM companies WHERE id=reference_id)
            THEN RAISE EXCEPTION 'briefing references unknown company'; END IF;
        END LOOP;
        IF jsonb_typeof(NEW.public_snapshot->'sourceBindings') IS DISTINCT FROM 'array'
            OR jsonb_array_length(NEW.public_snapshot->'sourceBindings') = 0
        THEN RAISE EXCEPTION 'briefing requires immutable source bindings'; END IF;
        FOR binding IN SELECT value FROM jsonb_array_elements(NEW.public_snapshot->'sourceBindings') LOOP
            IF jsonb_typeof(binding) IS DISTINCT FROM 'object'
                OR NOT (binding ?& ARRAY['documentId', 'documentVersion', 'grantId', 'grantRevision', 'recipients'])
                OR jsonb_typeof(binding->'documentId') IS DISTINCT FROM 'string' OR btrim(binding->>'documentId') = ''
                OR jsonb_typeof(binding->'documentVersion') IS DISTINCT FROM 'string' OR btrim(binding->>'documentVersion') = ''
                OR jsonb_typeof(binding->'grantId') IS DISTINCT FROM 'string' OR btrim(binding->>'grantId') = ''
                OR jsonb_typeof(binding->'grantRevision') IS DISTINCT FROM 'string' OR btrim(binding->>'grantRevision') = ''
                OR NOT briefing_read_identifier_array(binding->'recipients')
                OR jsonb_array_length(binding->'recipients') = 0
                OR NOT EXISTS (SELECT 1 FROM article_versions WHERE article_id=binding->>'documentId'
                    AND version=binding->>'documentVersion')
            THEN RAISE EXCEPTION 'invalid briefing source binding'; END IF;
        END LOOP;
        SELECT count(DISTINCT (value->>'documentId', value->>'documentVersion')) INTO binding_count
            FROM jsonb_array_elements(NEW.public_snapshot->'sourceBindings');
        IF binding_count <> jsonb_array_length(NEW.public_snapshot->'sourceBindings')
        THEN RAISE EXCEPTION 'duplicate briefing source binding'; END IF;
        FOR reference_id IN SELECT jsonb_array_elements_text(refs->'evidenceIds') LOOP
            IF NOT EXISTS (SELECT 1 FROM evidence e WHERE e.id=reference_id
                AND EXISTS (SELECT 1 FROM jsonb_array_elements(NEW.public_snapshot->'sourceBindings') AS b
                    WHERE b->>'documentId'=e.article_id AND b->>'documentVersion'=e.article_version))
            THEN RAISE EXCEPTION 'briefing references unknown or unbound evidence'; END IF;
        END LOOP;
        IF NEW.edition = 'morning' AND NEW.comparison_snapshot IS NOT NULL
        THEN RAISE EXCEPTION 'morning has no comparison'; END IF;
        IF NEW.edition = 'evening' AND NEW.comparison_snapshot IS NULL
        THEN RAISE EXCEPTION 'evening must preserve comparison or unavailable reason'; END IF;
        IF NEW.morning_round_id IS NOT NULL THEN
            SELECT * INTO morning FROM briefing_rounds WHERE id=NEW.morning_round_id FOR SHARE;
            IF NOT FOUND OR morning.edition <> 'morning' OR morning.round_date <> NEW.round_date
                OR morning.published_at IS NULL
            THEN RAISE EXCEPTION 'invalid morning comparison round'; END IF;
        END IF;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER briefing_read_round_guard BEFORE INSERT OR UPDATE OR DELETE ON briefing_rounds
    FOR EACH ROW EXECUTE FUNCTION protect_briefing_read_round();

CREATE FUNCTION protect_briefing_read_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r briefing_rounds; next_seq integer; previous_suspended boolean;
BEGIN
    IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'briefing change history is append-only'; END IF;
    SELECT * INTO r FROM briefing_rounds WHERE id=NEW.round_id FOR UPDATE;
    IF NOT FOUND OR r.published_at IS NULL THEN RAISE EXCEPTION 'only a published briefing can be changed'; END IF;
    SELECT COALESCE(MAX(seq), 0) + 1 INTO next_seq FROM briefing_changes WHERE round_id=NEW.round_id AND kind=NEW.kind;
    IF NEW.seq <> next_seq THEN RAISE EXCEPTION 'briefing change sequence must be consecutive'; END IF;
    IF NEW.created_at < r.published_at THEN RAISE EXCEPTION 'briefing change cannot precede publication'; END IF;
    IF NEW.kind = 'correction' AND NEW.event_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements(r.published_payload->'items') AS item WHERE item->>'eventId'=NEW.event_id)
    THEN RAISE EXCEPTION 'briefing correction references an unknown event'; END IF;
    IF NEW.kind = 'suspension' THEN
        SELECT suspended INTO previous_suspended FROM briefing_changes
            WHERE round_id=NEW.round_id AND kind='suspension' ORDER BY seq DESC LIMIT 1;
        IF NEW.suspended = COALESCE(previous_suspended, false)
        THEN RAISE EXCEPTION 'briefing suspension history must change the previous state'; END IF;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER briefing_read_change_guard BEFORE INSERT OR UPDATE OR DELETE ON briefing_changes
    FOR EACH ROW EXECUTE FUNCTION protect_briefing_read_change();

-- Both change-first and status-first transactions work, but neither half may commit by itself.
CREATE FUNCTION check_briefing_read_suspension() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE rid text; r briefing_rounds; is_suspended boolean;
BEGIN
    IF TG_TABLE_NAME='briefing_rounds' THEN rid := NEW.id; ELSE rid := NEW.round_id; END IF;
    SELECT * INTO r FROM briefing_rounds WHERE id=rid FOR UPDATE;
    IF NOT FOUND OR r.published_at IS NULL THEN RETURN NULL; END IF;
    SELECT suspended INTO is_suspended FROM briefing_changes
        WHERE round_id=rid AND kind='suspension' ORDER BY seq DESC LIMIT 1;
    IF (r.status='suspended') IS DISTINCT FROM COALESCE(is_suspended, false)
    THEN RAISE EXCEPTION 'briefing status and suspension history must commit together'; END IF;
    RETURN NULL;
END
$$;
CREATE CONSTRAINT TRIGGER briefing_read_round_suspension AFTER INSERT OR UPDATE ON briefing_rounds
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_briefing_read_suspension();
CREATE CONSTRAINT TRIGGER briefing_read_change_suspension AFTER INSERT ON briefing_changes
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_briefing_read_suspension();
