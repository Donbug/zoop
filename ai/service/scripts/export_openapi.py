#!/usr/bin/env python3
"""Generate docs/api/internal-ai-openapi.{json,yaml} from the service's own routes and models (service-owned tool).

`--check` writes nothing and exits 1 when either committed file differs from a fresh generation. The YAML is a deterministic
rendering of the same document as the JSON (strings are emitted as JSON strings, which are valid YAML), so the two cannot disagree.
The Submit/JobResult schemas are referenced from docs/api/ai-contract.schema.json and are never copied here.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from zoop_ai_service.app import create_app
from zoop_ai_service.openapi_doc import build

ROOT = Path(__file__).resolve().parents[3]
TARGETS = {"json": ROOT / "docs/api/internal-ai-openapi.json", "yaml": ROOT / "docs/api/internal-ai-openapi.yaml"}
SUBMIT_FIXTURE = ROOT / "ai/worker/fixtures/contracts/synthetic-document/jobs.json"


def yaml_lines(value: Any, indent: int = 0) -> list[str]:
    pad = "  " * indent
    if isinstance(value, dict):
        if not value:
            return [pad + "{}"]
        lines: list[str] = []
        for key, item in value.items():
            head = f"{pad}{json.dumps(str(key), ensure_ascii=False)}:"
            if isinstance(item, str) and "\n" in item and block_safe(item):
                lines.append(head + " |-")
                lines.extend(("  " * (indent + 1) + line) if line else "" for line in item.split("\n"))
            elif isinstance(item, (dict, list)) and item:
                lines.append(head)
                lines.extend(yaml_lines(item, indent + 1))
            else:
                lines.append(f"{head} {scalar(item)}")
        return lines
    if isinstance(value, list):
        if not value:
            return [pad + "[]"]
        lines = []
        for item in value:
            if isinstance(item, (dict, list)) and item:
                nested = yaml_lines(item, indent + 1)
                lines.append(f"{pad}- {nested[0].lstrip()}")
                lines.extend(nested[1:])
            else:
                lines.append(f"{pad}- {scalar(item)}")
        return lines
    return [pad + scalar(value)]


def block_safe(text: str) -> bool:
    """Literal block scalars only for plain prose: no leading/trailing space or tab, no control characters."""
    return text == text.strip("\n") and all(line == line.strip() and "\t" not in line and line.isprintable() for line in text.split("\n"))


def scalar(value: Any) -> str:
    if isinstance(value, dict):
        return "{}"
    if isinstance(value, list):
        return "[]"
    return json.dumps(value, ensure_ascii=False)


def generate() -> dict[str, str]:
    submit = json.loads(SUBMIT_FIXTURE.read_text(encoding="utf-8"))["jobs"][0]
    spec = build(create_app(), submit)
    header = ("# Generated by ai/service/scripts/export_openapi.py from the service's own routes and models; do not edit.\n"
              "# Submit and JobResult are referenced from ai-contract.schema.json, the single authority for the S1 wire contract.\n")
    return {"json": json.dumps(spec, ensure_ascii=False, indent=2) + "\n", "yaml": header + "\n".join(yaml_lines(spec)) + "\n"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed files differ from a fresh generation")
    check = parser.parse_args().check
    documents = generate()
    drift = [name for name, path in TARGETS.items() if not path.is_file() or path.read_text(encoding="utf-8") != documents[name]]
    if check:
        if drift:
            print("internal AI OpenAPI drift: " + ", ".join(str(TARGETS[name].relative_to(ROOT)) for name in drift)
                  + "; run ai/service/scripts/export_openapi.py", file=sys.stderr)
            return 1
        print("internal AI OpenAPI: generated JSON and YAML match the committed files.")
        return 0
    for name, path in TARGETS.items():
        path.write_text(documents[name], encoding="utf-8")
    print("wrote " + ", ".join(str(path.relative_to(ROOT)) for path in TARGETS.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
